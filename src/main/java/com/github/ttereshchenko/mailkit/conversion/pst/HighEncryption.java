    private HighEncryption() {}

    public static void decode(byte[] data, long bid) {
        int key = (int) bid;
        int salt = (((key & 0xffff0000) >>> 16) ^ (key & 0x0000ffff));

        for (int i = 0; i < data.length; i++) {
            int lowerSalt = salt & 0x00ff;
            int upperSalt = (salt & 0xff00) >>> 8;
            int index = data[i] & 0xFF;

            index += lowerSalt;
            index = HIGH_1[index & 0xFF] & 0xFF;
            index += upperSalt;
            index = HIGH_2[index & 0xFF] & 0xFF;
            index -= upperSalt;
            index = CompressibleEncryption.COMP_ENC[index & 0xFF] & 0xFF;
            index -= lowerSalt;

            data[i] = (byte) index;
            salt++;
        }
    }
